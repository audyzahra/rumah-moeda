<?php

namespace App\Services\Security;

class PatternList
{
    /**
     * Pola yang dilarang pada input.
     */
    public static function dangerousPatterns(): array
    {
        return [

            /*
            |--------------------------------------------------------------------------
            | PHP
            |--------------------------------------------------------------------------
            */

            '/<\?(php|=)?/i',

            /*
            |--------------------------------------------------------------------------
            | Script & HTML Berbahaya
            |--------------------------------------------------------------------------
            */

            '/<script\b/i',
            '/<\/script>/i',

            '/<iframe\b/i',
            '/<\/iframe>/i',

            '/<object\b/i',
            '/<\/object>/i',

            '/<embed\b/i',
            '/<\/embed>/i',

            '/<applet\b/i',
            '/<\/applet>/i',

            '/<meta\b/i',
            '/<base\b/i',
            '/<link\b/i',
            '/<svg\b/i',
            '/<math\b/i',

            /*
            |--------------------------------------------------------------------------
            | Event Handler
            |--------------------------------------------------------------------------
            */

            '/\son\w+\s*=/i',

            /*
            |--------------------------------------------------------------------------
            | JavaScript Protocol
            |--------------------------------------------------------------------------
            */

            '/javascript\s*:/i',
            '/vbscript\s*:/i',
            '/data\s*:\s*text\/html/i',

            /*
            |--------------------------------------------------------------------------
            | JavaScript Function
            |--------------------------------------------------------------------------
            */

            '/eval\s*\(/i',
            '/alert\s*\(/i',
            '/prompt\s*\(/i',
            '/confirm\s*\(/i',

            '/document\./i',
            '/window\./i',

            /*
            |--------------------------------------------------------------------------
            | SQL Injection
            |--------------------------------------------------------------------------
            */

            '/union\s+select/i',
            '/drop\s+table/i',
            '/truncate\s+table/i',
            '/delete\s+from/i',
            '/insert\s+into/i',
            '/update\s+.+set/i',

            /*
            |--------------------------------------------------------------------------
            | Blade
            |--------------------------------------------------------------------------
            */

            '/{{.*?}}/s',
            '/{!!.*?!!}/s',
            '/@php/i',

            /*
            |--------------------------------------------------------------------------
            | Shell Command
            |--------------------------------------------------------------------------
            */

            '/cmd\.exe/i',
            '/powershell/i',
            '/wget\s/i',
            '/curl\s/i',
            '/rm\s+-rf/i',
            '/chmod\s+/i',
            '/chown\s+/i',
        ];
    }
}
